    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Username dan Password tidak boleh kosong!", 
                "Peringatan", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean loginBerhasil = false;
        String namaPengguna = "";
        String role = "";

        // 1. Coba otentikasi melalui database MySQL XAMPP (table users)
        try {
            Connection conn = KoneksiDB.getConnection();
            String sql = "SELECT * FROM users WHERE username = ? AND password = ?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, username);
            ps.setString(2, password);
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                loginBerhasil = true;
                namaPengguna = rs.getString("nama_lengkap");
                role = rs.getString("role");
            }
        } catch (Exception e) {
            System.out.println("Catatan: Tidak terhubung ke database XAMPP, memeriksa kredensial fallback...");
        }

        // 2. Kredensial fallback bawaan (Admin & Direktur)
        if (!loginBerhasil) {
            if ((username.equalsIgnoreCase("admin") && password.equals("password")) ||
                (username.equalsIgnoreCase("admin") && password.equals("admin123")) ||
                (username.equalsIgnoreCase("axl") && password.equals("password"))) {
                loginBerhasil = true;
                namaPengguna = "Axl Regan Yohande (Direktur CV. AXL SARANA MANDIRI)";
                role = "ADMINISTRATOR";
            }
        }

        if (loginBerhasil) {
            JOptionPane.showMessageDialog(this,
                "LOGIN BERHASIL!\n\nSelamat Datang: " + namaPengguna + "\nRole: " + role + "\n\nSistem Pengadaan Sekolah - CV. AXL SARANA MANDIRI",
                "Informasi Login",
                JOptionPane.INFORMATION_MESSAGE);
            
            this.dispose();
            java.awt.EventQueue.invokeLater(() -> {
                new Main().bukaAplikasi();
            });
        } else {
            JOptionPane.showMessageDialog(this,
                "Username atau Password salah!\n\nAkun Uji Coba Default:\n- Username: admin\n- Password: password",
                "Login Gagal",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

